export function normalizeOfflineCategory(rawCategory?: string, assessmentType?: string): OfflineAssessmentCategory {
  const cat = (rawCategory || '').toUpperCase().trim();
  const title = (assessmentType || '').toUpperCase().trim();

  // 1. Exact Category Matches
  if (cat === 'CA' || cat === 'CONTINUOUS_ASSESSMENT') return 'CA';
  if (cat === 'QUIZ' || cat === 'CLASS_TEST' || cat === 'TEST') return 'QUIZ';
  if (cat === 'MIDTERM' || cat === 'MID_TERM' || cat === 'MID-TERM') return 'MIDTERM';
  if (cat === 'ASSIGNMENT' || cat === 'HOMEWORK' || cat === 'PROJECT') return 'ASSIGNMENT';
  if (cat === 'EXAM' || cat === 'TERMINAL' || cat === 'FINAL') return 'EXAM';

  // 2. Title-based Heuristic (Handles legacy records or defaulted enums)
  if (title.includes('CONTINUOUS') || title.includes('CA ') || title.startsWith('CA') || title.endsWith('CA')) return 'CA';
  if (title.includes('QUIZ') || title.includes('POP TEST') || title.includes('CLASS TEST')) return 'QUIZ';
  if (title.includes('MIDTERM') || title.includes('MID-TERM') || title.includes('MID TERM')) return 'MIDTERM';
  if (title.includes('ASSIGNMENT') || title.includes('HOMEWORK') || title.includes('PROJECT')) return 'ASSIGNMENT';
  if (title.includes('EXAM') || title.includes('TERMINAL') || title.includes('FINAL')) return 'EXAM';
  if (title.includes('TEST')) return 'QUIZ';

  // 3. Fallback to valid categories, default to CA
  if (['CA', 'QUIZ', 'MIDTERM', 'ASSIGNMENT', 'EXAM'].includes(cat)) {
    return cat as OfflineAssessmentCategory;
  }
  return 'CA';
}

export function isOfflineGradeRecord(g: any): boolean {
  if (!g) return false;

  // 1. Direct CBT attempts, Exam and Paper relations
  if (g.examAttemptId || g.subjectExamAttemptId) return false;
  if (g.examId || g.exam) return false;
  if (g.subjectPaperId || g.subjectPaper) return false;

  // 2. Online automated system IDs generated by CBT and Assignment engines
  const id = String(g.id || '');
  if (id.startsWith('grade-sa-') || id.startsWith('grade-total-') || id.startsWith('grade-assignment-')) {
    return false;
  }

  // 3. Online automated system remarks
  const remarks = String(g.remarks || '').toLowerCase();
  if (
    remarks.startsWith('subject results for') ||
    remarks.startsWith('overall total for') ||
    remarks.includes('assignment submission')
  ) {
    return false;
  }

  return true;
}

interface OfflineGradesDashboardProps {
  defaultClassId?: string;
  schoolId?: string;
  hideClassFilter?: boolean;
  teacherClassDetail?: any;
}

export default function OfflineGradesDashboard({
  defaultClassId,
  schoolId: propSchoolId,
  hideClassFilter,
  teacherClassDetail,
}: OfflineGradesDashboardProps) {
  const queryClient = useQueryClient();
  const searchParams = useSearchParams();
  const urlClassId = searchParams.get('classId');
  const activeClassId = defaultClassId || urlClassId || undefined;

  const { user } = useAuthStore();
  const { selectedSchoolId } = useDashboardStore();
  const { data: teacherProfile } = useTeacherProfile();
  const { data: linkedSchoolsData } = useTeacherLinkedSchools();

  const userSchoolId =
    (user as any)?.schoolId ||
    (user as any)?.school?.id ||
    user?.schools?.[0]?.schoolId ||
    (user as any)?.tenantId ||
    (teacherProfile as any)?.activeSchoolId ||
    (teacherProfile as any)?.primarySchoolId ||
    (teacherProfile as any)?.schoolId ||
    '';

  const isTeacher = user?.userType === 'TEACHER';

  const currentTeacherId = (user as any)?.id as string | undefined;
  const effectiveSelectedSchoolId =
    selectedSchoolId && selectedSchoolId !== currentTeacherId ? selectedSchoolId : '';

  const baseSchoolId =
    propSchoolId ||
    effectiveSelectedSchoolId ||
    userSchoolId ||
    linkedSchoolsData?.[0]?.id ||
    '';

  const { data: teacherClassesData } = useTeacherClasses(isTeacher ? (baseSchoolId || undefined) : undefined);

  // Matched class school ID if a class is active
  const matchedClassSchoolId = useMemo(() => {
    if (!activeClassId || !Array.isArray(teacherClassesData)) return undefined;
    const match = teacherClassesData.find((c: any) => c.id === activeClassId || c.classId === activeClassId);
    return match?.schoolId || (match as any)?.school?.id;
  }, [activeClassId, teacherClassesData]);

  // First linked school fallback if teacher has connected schools
  const firstLinkedSchoolId = useMemo(() => {
    if (!Array.isArray(linkedSchoolsData) || linkedSchoolsData.length === 0) return undefined;
    return linkedSchoolsData[0]?.id;
  }, [linkedSchoolsData]);

  const schoolId =
    propSchoolId ||
    matchedClassSchoolId ||
    baseSchoolId ||
    firstLinkedSchoolId ||
    '';

  const { data: schoolProfile } = useSchoolProfile(schoolId);
  const { data: teacherSubjectsData } = useTeacherSubjects(isTeacher ? (schoolId || undefined) : undefined);

  const teacherSubjectIdSet = useMemo(() => {
    if (!isTeacher || !teacherSubjectsData) return new Set<string>();
    return new Set(
      teacherSubjectsData
        .map((s: any) => (s.id || s.subjectId || s.subject?.id || '').toString())
        .filter(Boolean)
    );
  }, [isTeacher, teacherSubjectsData]);

  const teacherClassSubjectIdSet = useMemo(() => {
    if (!isTeacher) return new Set<string>();

    const ids: string[] = [];

    if (activeClassId) {
      const classMatch = Array.isArray(teacherClassesData)
        ? teacherClassesData.find((c: any) => c.id === activeClassId || c.classId === activeClassId)
        : null;

      const classSubjectIds = Array.isArray((classMatch as any)?.teacherSubjectIds)
        ? (classMatch as any).teacherSubjectIds
        : Array.isArray((classMatch as any)?.subjects)
          ? (classMatch as any).subjects
            .map((s: any) => s?.subjectId || s?.id || s?.subject?.id)
            .filter(Boolean)
          : [];

      const fallback = Array.isArray((classMatch as any)?.classInfo?.teacherSubjectIds)
        ? (classMatch as any).classInfo.teacherSubjectIds
        : [];

      const detailIds = Array.isArray(teacherClassDetail?.classInfo?.teacherSubjectIds)
        ? teacherClassDetail.classInfo.teacherSubjectIds
        : [];

      ids.push(...classSubjectIds, ...fallback, ...detailIds);
    } else if (Array.isArray(teacherClassesData)) {
      // Gather across all classes taught by teacher
      teacherClassesData.forEach((c: any) => {
        if (c.subjectId) ids.push(String(c.subjectId));
        if (Array.isArray(c.teacherSubjectIds)) ids.push(...c.teacherSubjectIds.map(String));
        if (Array.isArray(c.subjects)) {
          c.subjects.forEach((s: any) => {
            const sid = s?.subjectId || s?.id || s?.subject?.id;
            if (sid) ids.push(String(sid));
          });
        }
      });
    }

    return new Set<string>(ids.filter(Boolean));
  }, [activeClassId, isTeacher, teacherClassesData, teacherClassDetail]);

  const teacherScopeSubjectIds = useMemo(() => {
    if (!isTeacher) return new Set<string>();
    const set = new Set<string>();
    Array.from(teacherSubjectIdSet).forEach((id) => set.add(String(id)));
    return set;
  }, [isTeacher, teacherSubjectIdSet]);

  const teacherSubjectNames = useMemo(() => {
    if (!isTeacher) return null;
    const names = new Set<string>();

    if (Array.isArray(teacherSubjectsData)) {
      teacherSubjectsData.forEach((s: any) => {
        const name = (s.name || s.subject?.name || '').trim().toLowerCase();
        if (name) names.add(name);
        const code = (s.code || s.subject?.code || '').trim().toLowerCase();
        if (code) names.add(code);
      });
    }

    // Extract focus subject from teacher user profile if available
    const userSubjectStr = (user as any)?.subject;
    if (typeof userSubjectStr === 'string' && userSubjectStr) {
      userSubjectStr.split(',').forEach((sub: string) => {
        const trimmed = sub.trim().toLowerCase();
        if (trimmed) names.add(trimmed);
      });
    }

    return names;
  }, [isTeacher, teacherSubjectsData, user]);

  const teacherScopeSubjectNames = useMemo(() => {
    if (!isTeacher || !teacherSubjectNames) return new Set<string>();
    const set = new Set<string>();
    Array.from(teacherSubjectNames).forEach((name) => set.add(String(name)));
    return set;
  }, [isTeacher, teacherSubjectNames]);

  // 1. Fetch school classes & sessions
  const { data: classesData, isLoading: isLoadingClasses } = useClasses(schoolId);
  const classes = useMemo(() => {
    if (isTeacher && Array.isArray(teacherClassesData) && teacherClassesData.length > 0) {
      return teacherClassesData;
    }
    const list = Array.isArray(classesData?.data) ? classesData.data : (Array.isArray(classesData) ? classesData : []);
    return list;
  }, [isTeacher, teacherClassesData, classesData]);

  const { data: sessionsData } = useSessions(schoolId);
  const sessions = useMemo(() => {
    const list = Array.isArray(sessionsData?.data) ? sessionsData.data : (Array.isArray(sessionsData) ? sessionsData : []);
    return list;
  }, [sessionsData]);

  // 2. Fetch all offline assessment records
  const { data: recordsData, isLoading: isLoadingRecords } = useQuery({
    queryKey: ['offline-grades-history', schoolId, activeClassId],
    queryFn: async () => {
      const res = await gradeService.getGradeHub(schoolId, {
        classId: activeClassId || undefined,
        offlineOnly: 'true',
        limit: 1000,
      });
      const grades = Array.isArray(res?.data)
        ? res.data
        : (Array.isArray(res?.grades) ? res.grades : (Array.isArray(res) ? res : []));

      // Group offline grades by normalized category + assessmentType + classId + subject + term
      const groupMap = new Map<string, GradeBatchSummary & { _scoreSum?: number }>();

      grades.forEach((g: any) => {
        // Strictly only include physical / manual offline grade records
        if (!isOfflineGradeRecord(g)) return;

        // If activeClassId is defined, only include matching class
        if (activeClassId && g.classId !== activeClassId) return;

        // Determine if this grade record matches the teacher's assigned subjects
        const sId = (g.subjectId || g.subject?.id || g.subjectPaper?.subject?.id || '').toString();
        const sName = (g.subject || g.subjectName || g.subjectPaper?.subject?.name || '').toString().trim().toLowerCase();
        const isMatchedSubject = Boolean(
          (sId && teacherScopeSubjectIds?.has(sId)) ||
          (sName && (
            teacherScopeSubjectNames?.has(sName) ||
            Array.from(teacherScopeSubjectNames || []).some(assignedName =>
              sName.includes(assignedName) || assignedName.includes(sName)
            )
          ))
        );

        // If teacher, scope to records in teacher's assigned classes, assigned subjects, or created by the teacher
        if (isTeacher) {
          const isCreatedByTeacher = g.teacherId && (g.teacherId === user?.id || (user as any)?.teacherId === g.teacherId);
          const isAssignedClass = Boolean(
            g.classId && Array.isArray(teacherClassesData) && teacherClassesData.some((c: any) => c.id === g.classId || c.classId === g.classId)
          );

          if (!isCreatedByTeacher && !isAssignedClass && !isMatchedSubject) {
            return;
          }
        }

        const classObj = classes.find((c: any) => c.id === g.classId);
        const resolvedClassName = classObj?.name
          ? `${classObj.name} ${classObj.section || ''}`.trim()
          : (g.class?.name ? `${g.class.name} ${g.class.section || ''}`.trim() : 'General Class');

        const resolvedCategory = normalizeOfflineCategory(g.category, g.assessmentType);
        const assessmentTitle = g.assessmentType || `${resolvedCategory} Assessment`;
        const key = `${g.classId || 'noclass'}_${(g.subject || '').trim().toLowerCase()}_${resolvedCategory}_${assessmentTitle.trim().toLowerCase()}_${g.term || 'FIRST'}`;
        const existingGroup = groupMap.get(key);

        const hasScore = g.score !== null && g.score !== undefined && !isNaN(Number(g.score));
        const numScore = hasScore ? Number(g.score) : 0;
        const isAdminUser = !isTeacher && user?.name;
        const fallbackAdminName = isAdminUser ? `Admin: ${user.name}` : null;
        const resolvedTeacherName = g.creatorName || g.teacher?.name || (g.teacherId === user?.id ? (isAdminUser ? fallbackAdminName : (user?.name || 'You')) : fallbackAdminName);

        if (existingGroup) {
          existingGroup.totalStudents += 1;
          if (hasScore) {
            existingGroup.gradedStudents += 1;
            const newScoreSum = (existingGroup._scoreSum || 0) + numScore;
            existingGroup._scoreSum = newScoreSum;
            existingGroup.averageScore = newScoreSum / existingGroup.gradedStudents;
          }
          if (!existingGroup.teacherName && resolvedTeacherName) {
            existingGroup.teacherName = resolvedTeacherName;
            existingGroup.teacherId = g.teacherId || g.teacher?.id;
            existingGroup.teacherCode = g.teacher?.teacherCode;
          }
          if (isMatchedSubject) {
            existingGroup.isAssignedSubject = true;
          }
          // Preserve latest activity/creation date
          if (g.createdAt && new Date(g.createdAt) > new Date(existingGroup.createdAt)) {
            existingGroup.createdAt = g.createdAt;
          }
          if (g.updatedAt && new Date(g.updatedAt) > new Date(existingGroup.updatedAt)) {
            existingGroup.updatedAt = g.updatedAt;
          }
        } else {
          groupMap.set(key, {
            id: g.id,
            classId: g.classId || '',
            className: resolvedClassName,
            subject: g.subject || 'General',
            category: resolvedCategory,
            assessmentType: assessmentTitle,
            maxMarks: g.maxMarks || (resolvedCategory === 'CA' ? 20 : (resolvedCategory === 'QUIZ' ? 10 : (resolvedCategory === 'MIDTERM' ? 40 : 100))),
            term: g.term || 'FIRST',
            sessionId: g.sessionId || '',
            totalStudents: 1,
            gradedStudents: hasScore ? 1 : 0,
            averageScore: numScore,
            status: g.status || 'DRAFT',
            releaseDate: g.releaseDate || undefined,
            createdAt: g.createdAt || new Date().toISOString(),
            updatedAt: g.updatedAt || new Date().toISOString(),
            teacherId: g.teacherId || g.teacher?.id || null,
            teacherName: resolvedTeacherName,
            teacherCode: g.teacher?.teacherCode || null,
            _scoreSum: numScore,
            isAssignedSubject: isMatchedSubject,
          });
        }
      });

      // Sort by date descending (newest assessment records first)
      const list = Array.from(groupMap.values());
      list.sort((a, b) => {
        const timeA = new Date(a.createdAt || a.updatedAt || 0).getTime();
        const timeB = new Date(b.createdAt || b.updatedAt || 0).getTime();
        return timeB - timeA;
      });

      return list;
    },
    enabled: !!schoolId,
    staleTime: 1000 * 60 * 3,
  });

  const records = recordsData || [];

  // Modal State for Entering/Editing Grades, Sync Pop-up & Institutional Export
  const [isScoreModalOpen, setIsScoreModalOpen] = useState(false);
  const [isSyncModalOpen, setIsSyncModalOpen] = useState(false);
  const [isExportModalOpen, setIsExportModalOpen] = useState(false);
  const [recordForExport, setRecordForExport] = useState<GradeBatchSummary | null>(null);
  const [selectedRecordForEdit, setSelectedRecordForEdit] = useState<GradeBatchSummary | null>(null);
  const [defaultCategoryForNew, setDefaultCategoryForNew] = useState<OfflineAssessmentCategory | undefined>();
  const [defaultClassIdForNew, setDefaultClassIdForNew] = useState<string | undefined>();
  const [defaultSubjectForNew, setDefaultSubjectForNew] = useState<string | undefined>();
  const [defaultMaxMarksForNew, setDefaultMaxMarksForNew] = useState<number | undefined>();
  const [initialScoresForNew, setInitialScoresForNew] = useState<Record<string, { score: number; remarks?: string }> | undefined>();

  const handleAddNewRecord = (category?: OfflineAssessmentCategory) => {
    setSelectedRecordForEdit(null);
    setDefaultCategoryForNew(category);
    setDefaultClassIdForNew(activeClassId || undefined);
    setDefaultSubjectForNew(undefined);
    setDefaultMaxMarksForNew(undefined);
    setInitialScoresForNew(undefined);
    setIsScoreModalOpen(true);
  };

  const handleAddNewRecordWithSetup = (setup: {
    classId: string;
    className?: string;
    subject: string;
    category: OfflineAssessmentCategory;
    maxMarks: number;
    initialScores?: Record<string, { score: number; remarks?: string }>;
  }) => {
    setSelectedRecordForEdit(null);
    setDefaultClassIdForNew(setup.classId);
    setDefaultSubjectForNew(setup.subject);
    setDefaultCategoryForNew(setup.category);
    setDefaultMaxMarksForNew(setup.maxMarks);
    setInitialScoresForNew(setup.initialScores);
    setIsScoreModalOpen(true);
  };

  const handleEditRecord = (record: GradeBatchSummary) => {
    setSelectedRecordForEdit(record);
    setIsScoreModalOpen(true);
  };

  const handleDeleteRecord = async (recordId: string, record?: GradeBatchSummary) => {
    try {
      const criteria = record ? {
        classId: record.classId,
        subject: record.subject,
        assessmentType: record.assessmentType,
        category: record.category,
        term: record.term,
      } : undefined;

      const res = await gradeService.deleteBatchGrades(recordId, criteria);
      const count = res?.data?.count || 1;
      toast.success(`Successfully deleted offline assessment marksheet (${count} student ${count === 1 ? 'grade' : 'grades'} removed).`);
      queryClient.invalidateQueries({ queryKey: ['offline-grades-history'] });
      queryClient.invalidateQueries({ queryKey: ['grades'] });
      queryClient.invalidateQueries({ queryKey: ['gradeHub'] });
    } catch (err: any) {
      toast.error(err?.response?.data?.error || err?.response?.data?.message || err?.message || 'Failed to delete offline record.');
    }
  };

  // Export handlers
  const handleExportPDF = (record?: GradeBatchSummary) => {
    const activeGradingSystem = schoolProfile?.gradingSystem;
    if (record) {
      const pct = record.maxMarks > 0 ? Math.round((record.averageScore / record.maxMarks) * 100) : 0;
      const gradePill = computeGradePill(pct, activeGradingSystem);
      // Export single record summary
      generatePDF({
        title: `Offline Assessment Marksheet — ${record.assessmentType}`,
        filename: `Marksheet_${record.subject}_${record.className.replace(/\s+/g, '_')}.pdf`,
        schoolProfile,
        orientation: 'portrait',
        metaData: [
          { label: 'Class', value: record.className },
          { label: 'Subject Curriculum', value: record.subject },
          { label: 'Assessment Category', value: record.category },
          { label: 'Max Score Marks', value: String(record.maxMarks) },
          { label: 'Graded Students', value: `${record.gradedStudents} students` },
          { label: 'Class Average', value: `${record.averageScore.toFixed(1)} / ${record.maxMarks} (${pct}% - ${gradePill.label})` },
          { label: 'Status', value: record.status || 'DRAFT' },
        ],
        tableHeaders: [['Item', 'Subject', 'Class', 'Category', 'Average Score', 'Grade', 'Status']],
        tableData: [[
          record.assessmentType,
          record.subject,
          record.className,
          record.category,
          `${record.averageScore.toFixed(1)} / ${record.maxMarks} (${pct}%)`,
          `${gradePill.label} (${gradePill.remark})`,
          record.status || 'DRAFT'
        ]],
      });
    } else {
      // Export all records directory
      generatePDF({
        title: 'Offline Assessment Records Directory',
        filename: 'Offline_Assessment_Records_Directory.pdf',
        schoolProfile,
        orientation: 'landscape',
        metaData: [
          { label: 'Total Records', value: `${records.length} assessments` },
          { label: 'Export Date', value: new Date().toLocaleDateString() },
        ],
        tableHeaders: [['#', 'Assessment Title', 'Subject', 'Class', 'Category', 'Graded Students', 'Average Score', 'Grade', 'Status']],
        tableData: records.map((r, idx) => {
          const pct = r.maxMarks > 0 ? Math.round((r.averageScore / r.maxMarks) * 100) : 0;
          const gradePill = computeGradePill(pct, activeGradingSystem);
          return [
            String(idx + 1),
            r.assessmentType,
            r.subject,
            r.className,
            r.category,
            String(r.gradedStudents),
            `${r.averageScore.toFixed(1)} / ${r.maxMarks} (${pct}%)`,
            gradePill.label,
            r.status
          ];
        }),
      });
    }
  };

  const handleExportCSV = (record?: GradeBatchSummary) => {
    const activeGradingSystem = schoolProfile?.gradingSystem;
    const list = record ? [record] : records;
    const headers = ['#', 'Assessment Title', 'Subject', 'Class', 'Category', 'Graded Students', 'Average Score', 'Max Marks', 'Percentage', 'Letter Grade', 'Remark', 'Status'];
    const rows = list.map((r, idx) => {
      const pct = r.maxMarks > 0 ? Math.round((r.averageScore / r.maxMarks) * 100) : 0;
      const gradePill = computeGradePill(pct, activeGradingSystem);
      return [
        idx + 1,
        `"${r.assessmentType.replace(/"/g, '""')}"`,
        `"${r.subject.replace(/"/g, '""')}"`,
        `"${r.className.replace(/"/g, '""')}"`,
        r.category,
        r.gradedStudents,
        r.averageScore.toFixed(1),
        r.maxMarks,
        `${pct}%`,
        gradePill.label,
        `"${(gradePill.remark || '').replace(/"/g, '""')}"`,
        r.status
      ];
    });

    const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `Offline_Assessment_Records_${Date.now()}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="w-full max-w-full space-y-6">
      {/* Primary View: Directory of Offline Assessment Records */}
      <OfflineRecordsList
        records={records}
        classes={classes}
        isLoading={isLoadingRecords || isLoadingClasses}
        isTeacher={isTeacher}
        hideClassFilter={hideClassFilter ?? !!defaultClassId}
        activeClassId={activeClassId}
        gradingSystem={schoolProfile?.gradingSystem}
        onAddNewRecord={handleAddNewRecord}
        onEditRecord={handleEditRecord}
        onDeleteRecord={handleDeleteRecord}
        onExportPDF={handleExportPDF}
        onExportCSV={handleExportCSV}
        onOpenSyncModal={() => setIsSyncModalOpen(true)}
        onOpenExportModal={(rec) => {
          setRecordForExport(rec || null);
          setIsExportModalOpen(true);
        }}
      />

      {/* Offline Grade Sheet Sync Pop-up Modal (Hidden by default, shows on button click) */}
      {isSyncModalOpen && (
        <OfflineGradeSheetSyncModal
          isOpen={isSyncModalOpen}
          onClose={() => setIsSyncModalOpen(false)}
          classes={classes}
          schoolId={schoolId}
          schoolName={schoolProfile?.name}
          sessions={sessions}
          isTeacher={isTeacher}
          teacherSubjects={Array.isArray(teacherSubjectsData) ? teacherSubjectsData : []}
          activeClassId={activeClassId}
          onOpenRecordModalWithSetup={handleAddNewRecordWithSetup}
        />
      )}

      {/* Score Entry / Edit Modal */}
      {isScoreModalOpen && (
        <RecordScoreEntryModal
          key={selectedRecordForEdit ? `edit-${selectedRecordForEdit.id}` : `new-${defaultClassIdForNew || activeClassId || 'empty'}-${Date.now()}`}
          isOpen={isScoreModalOpen}
          onClose={() => {
            setIsScoreModalOpen(false);
            setSelectedRecordForEdit(null);
            setDefaultCategoryForNew(undefined);
            setDefaultClassIdForNew(undefined);
            setDefaultSubjectForNew(undefined);
            setDefaultMaxMarksForNew(undefined);
            setInitialScoresForNew(undefined);
          }}
          schoolId={schoolId}
          gradingSystem={schoolProfile?.gradingSystem}
          classes={classes}
          sessions={sessions}
          initialRecord={selectedRecordForEdit}
          defaultCategory={defaultCategoryForNew}
          defaultClassId={defaultClassIdForNew || activeClassId}
          defaultSubject={defaultSubjectForNew}
          defaultMaxMarks={defaultMaxMarksForNew}
          initialScores={initialScoresForNew}
          onSavedSuccess={() => {
            queryClient.invalidateQueries({ queryKey: ['offline-grades-history'] });
          }}
        />
      )}

      {/* Institutional Offline Grades Export Modal */}
      <OfflineGradesExportModal
        isOpen={isExportModalOpen}
        onClose={() => {
          setIsExportModalOpen(false);
          setRecordForExport(null);
        }}
        records={records}
        singleRecord={recordForExport}
        className={classes.find((c: { id?: string; name?: string }) => c.id === activeClassId)?.name}
        schoolProfile={schoolProfile}
        schoolId={schoolId}
        teacherName={user?.name || user?.email || 'Teacher'}
        teacherId={user?.id}
        isTeacher={isTeacher}
        gradingSystem={schoolProfile?.gradingSystem}
      />
    </div>
  );
}
